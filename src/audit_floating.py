"""Trace the layout's floating net and demonstrate its readout-only effect."""
import argparse
from collections import Counter
import json
import os
from pathlib import Path
import pickle

from reproduce import read_answer


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--results', type=Path, required=True)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    results, out = args.results.resolve(), args.out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    os.chdir(Path(__file__).resolve().parent)
    from sim import Netlist
    source = json.loads((results/'netlist.json').read_text())
    # Load only the JSON netlist generated by this reproduction, not an external pickle.
    local_pickle = out/'floating_netlist.pkl'
    local_pickle.write_bytes(pickle.dumps(source))
    nl = Netlist(str(local_pickle))
    required = {n for _, _, inputs in nl.gates for n in inputs}
    required |= {f[2] for f in nl.ffs}
    undriven = sorted(required-set(nl.driver), key=str)
    assert len(undriven) == 1, undriven
    net = undriven[0]
    sinks = []
    for cell in source['cells']:
        for pin, nets in cell['pins'].items():
            if net in nets:
                sinks.append({'instance_index':cell['idx'],'cell':cell['cell'],
                              'pin':pin,'origin_nm':cell['origin']})
    outputs = [o for _, o, _ in nl.gates] + [f[1] for f in nl.ffs]
    multiple = {str(n):c for n,c in Counter(outputs).items() if c>1}
    assert not multiple, multiple
    verification = json.loads((results/'verification.json').read_text())
    bits = [int(b) for b in verification['input_bits']]
    adjacent = bits.copy()
    for index in (0,7,11,18): adjacent[index] ^= 1
    outcomes = {}
    for value in (0,1):
        # Diagnostic assumption: give the undriven net a fixed binary value.
        # This changes no extracted connectivity and is not a physical repair.
        nl.const[net] = value
        outcomes[str(value)] = {'winning':read_answer(nl,bits),
                                'adjacent':read_answer(nl,adjacent)}
    nl.const.pop(net)
    assert outcomes['0']['winning'] == outcomes['1']['winning']
    assert outcomes['0']['adjacent']['success_trace'] == [0]*16
    assert outcomes['1']['adjacent']['success_trace'] == [0]*16
    assert outcomes['0']['adjacent']['text'] == 'TWO"NOT TOUCH'
    result = {'undriven_net':net,'sink_pins':sinks,'multiple_driver_nets':multiple,
              'binary_assumption_experiments':outcomes,
              'winning_output_independent_of_floating_value':True,
              'adjacency_rejection_independent_of_floating_value':True,
              'limitation':'A floating physical input has no defined digital value; 0 and 1 are diagnostic assumptions, not analog predictions.'}
    (out/'floating_wire.json').write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(result,indent=2))


if __name__ == '__main__':
    main()
